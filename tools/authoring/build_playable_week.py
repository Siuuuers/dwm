#!/usr/bin/env python3
"""Prepare authored DTL and explicit bindings; Godot owns compilation and hashes."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'story/auditions/playable-week-20261023'
OUTCOMES = ('never_started', 'unfinished', 'won', 'lost', 'perfect')


class Week:
    def __init__(self):
        self.entries = []
        self.sources = {day: (SOURCE / f'day-{day}.md').read_text().splitlines()
                        for day in range(1, 8)}

    def read(self, day, start, end):
        result = []
        for number in range(start, end + 1):
            raw = self.sources[day][number - 1].strip()
            if not raw or raw.startswith('#'):
                continue
            if any(raw.startswith(prefix) for prefix in (
                '**[Author', '**Author boundary', '*Control:', '*(Read ',
                '*(Follow ', '*The visible scene cuts', '**Self-talk — Aftermath',
                '- *No input', '- *Option', '> **Unmarked perceptual shard')):
                continue
            raw = raw.removeprefix('> ').strip()
            # Structural self-talk labels are author annotations, not dialogue.
            raw = re.sub(r'^\*\*(?:Optional thought(?: \(Route Fork\))?|Self-talk(?: — [^:*]+)?|Private self-talk(?: — [^:*]+)?):\*\*\s*', '', raw)
            if re.fullmatch(r'\*\*(?:Private self-talk|Self-talk)[^*]*\*\*', raw):
                continue
            raw = re.sub(r'\*\*([^*]+)\*\*', r'\1', raw)
            raw = re.sub(r'(?<!\*)\*([^*]+)\*(?!\*)', r'\1', raw)
            raw = re.sub(r'~~([^~]+)~~', lambda m: ''.join(c + '\u0336' for c in m[1]), raw)
            raw = raw.replace('`', '')
            if raw:
                result.append({'text': raw, 'source_line': number, 'source_day': day})
        return result

    @staticmethod
    def join(*groups):
        return [block for group in groups for block in group]

    def scene(self, id, day, blocks, terminal, role='scene'):
        assert re.fullmatch(r'[A-Za-z0-9_.]+', id), id
        assert blocks, id
        assert all(entry['id'] != id for entry in self.entries), id
        self.entries.append({'id': id, 'day': day, 'lines': blocks,
                             'terminal': terminal, 'role': role})

    def write(self):
        output = ROOT / 'dialogic/timelines/authored_week'
        if any(output.glob('Day*.dtl')):
            raise SystemExit(
                'Refusing to overwrite authored DTL: this historical importer assigns '
                'ordinal IDs. Edit existing DTL directly, retain each #id, give new '
                'captions new IDs, and regenerate registration with '
                'tools/authoring/ExportSevenDayRegistration.gd on the cloud runner.')
        ids = {entry['id'] for entry in self.entries}
        challenges = []
        output.mkdir(parents=True, exist_ok=True)
        days = {day: ['# Generated by tools/authoring/build_playable_week.py. Edit the source adapter, then regenerate.', 'return', ''] for day in range(1, 8)}
        entries = []
        for entry in self.entries:
            id, day, terminal = entry['id'], entry['day'], entry['terminal']
            rows = days[day]
            rows += ['label ' + id]
            lines = []
            for index, block in enumerate(entry['lines'], 1):
                text = block['text'].strip()
                assert text and not any(c in text for c in '\n\r[{<'), (id, text)
                # Retain the day-entry witness IDs used by Gallery unlocks.
                line_id = f'line.{id}.one' if id == f'Day{day}' and index == 1 else f'line.{id}.{index:03d}'
                # Dialogic colons otherwise create dynamic characters. Leading
                # backslash makes prose literal, including command-like words.
                rows.append('\\' + text.replace(':', '\\:') + ' #id:' + line_id)
                lines.append(dict(block, line_id=line_id))
            last = lines[-1]['line_id']
            markers = []

            def target(destination):
                assert destination in ids, (id, destination)
                return 'target.' + destination

            def marker(suffix, kind, payload):
                marker_id = id + '.' + suffix
                markers.append({'marker_id': marker_id, 'label': marker_id,
                                'after_line_id': last, 'kind': kind, 'payload': payload})
                rows.append('label ' + marker_id)
                return marker_id

            kind = terminal['kind']
            if kind == 'next':
                marker('next', 'scene.transition', {'target_id': target(terminal['target'])})
            elif kind == 'thought':
                marker('thought', 'thought.pass', {'opportunity_id': terminal['opportunity_id'],
                    'yes_target_id': target(terminal['yes']), 'pass_target_id': target(terminal['default'])})
            elif kind == 'options':
                marker('thought', 'thought.options', {'opportunity_id': terminal['opportunity_id'],
                    'options': [{'choice_id': o['choice_id'], 'text': o['text'], 'target_id': target(o['target'])}
                                for o in terminal['options']], 'pass_target_id': target(terminal['default'])})
            elif kind == 'challenge':
                challenge_id = terminal['challenge_id']
                playable = marker('playable', 'challenge.playable', {'challenge_id': challenge_id})
                end = marker('end', 'challenge.end', {'challenge_id': challenge_id})
                challenges.append({'challenge_id': challenge_id, 'entry_id': id,
                    'playable_marker_id': playable, 'end_marker_id': end,
                    'board_profile_id': 'week.canonical_solo',
                    'targets': {o: target(terminal['targets'][o]) for o in OUTCOMES}})
            elif kind == 'recall':
                marker('echo', 'challenge.recall', dict(challenge_id=terminal['challenge_id'],
                    **{o + '_target_id': target(terminal['targets'][o]) for o in OUTCOMES}))
            else:
                assert kind == 'end' and entry['role'] == 'ending', (id, terminal)
            rows += ['return', '']
            entries.append({'entry_id': id, 'path': f'res://dialogic/timelines/authored_week/Day{day}.dtl',
                            'role': entry['role'], 'story_day': day, 'markers': markers, 'lines': lines})
        challenge_ids = {row['challenge_id'] for row in challenges}
        assert len(challenge_ids) == len(challenges)
        for entry in entries:
            for item in entry['markers']:
                if item['kind'] == 'challenge.recall':
                    assert item['payload']['challenge_id'] in challenge_ids
        for day, rows in days.items():
            (output / f'Day{day}.dtl').write_text('\n'.join(rows) + '\n')
        manifest = {'kind': 'authored_week_source', 'schema_version': 1,
                    'first_entry_id': 'Day1', 'entries': entries, 'challenges': challenges}
        (ROOT / 'data/manifests/authored_week_source.json').write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
        art_path = ROOT / 'data/manifests/art_placements.json'
        art = json.loads(art_path.read_text())
        for entry in self.entries:
            if entry['role'] != 'ending':
                art['scenes'][entry['id']] = dict(art['scenes'][f'Day{entry["day"]}'])
        art_path.write_text(json.dumps(art, ensure_ascii=False, indent=2) + '\n')
        print(f'Prepared {len(entries)} scenes, {sum(len(e["lines"]) for e in entries)} captions, {len(challenges)} Challenge registrations')


if __name__ == '__main__':
    import story_days_1_3
    import story_days_4_7
    week = Week()
    story_days_1_3.build(week)
    story_days_4_7.build(week)
    week.write()
